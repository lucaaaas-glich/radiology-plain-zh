"""Evaluate a separately frozen postprocessing arm without new model calls."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import radplain
from radplain.recheck_v2 import recheck
from scripts.v2_local_preflight import committed, digest


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--input', required=True, type=Path)
    p.add_argument('--reports', required=True, type=Path)
    p.add_argument('--original-runtime', required=True, type=Path)
    p.add_argument('--out', required=True, type=Path)
    p.add_argument('--split', required=True, choices=['synthetic', 'real'])
    p.add_argument('--stage', required=True, choices=['development', 'final'])
    p.add_argument('--candidate-lock', type=Path)
    a = p.parse_args()
    original_runtime = json.loads(a.original_runtime.read_text())
    if a.out.exists():
        p.error('Never overwrite a prior run')
    if a.split == 'real' and not a.out.resolve().is_relative_to(Path('results/v2/real-data').resolve()):
        p.error('Real output must remain in ignored results/v2/real-data')
    if a.stage == 'final':
        barrier_path = Path('examples/v2/final_inspection_barrier.json')
        committed(barrier_path)
        barrier = json.loads(barrier_path.read_text())
        if barrier['state'] != 'released' or not a.candidate_lock:
            p.error('Final recheck needs released barrier and committed candidate lock')
        committed(a.candidate_lock)
        if barrier.get('additional_candidate_locks', {}).get(str(a.candidate_lock)) != digest(a.candidate_lock):
            p.error('Recheck arm was not bound to the committed inspection release')
        lock = json.loads(a.candidate_lock.read_text())
        if digest(a.reports) != lock['holdout_sha256'][a.split]:
            p.error('Frozen input reports changed')
        if original_runtime['candidate_lock_sha256'] != lock['original_gpu_candidate_lock_sha256']:
            p.error('Original predictions were generated by a different GPU candidate')
        for path, sha in lock['code_sha256'].items():
            committed(path)
            if digest(path) != sha:
                raise ValueError('Frozen recheck code changed: '+path)
    if original_runtime.get('source_changed_during_run'):
        raise ValueError('Original run changed its code')
    rows = [json.loads(s) for s in a.input.read_text().splitlines() if s.strip()]
    reports = [json.loads(s) for s in a.reports.read_text().splitlines() if s.strip()]
    if [(r['id'],r['report']) for r in rows] != [(r['id'],r['report']) for r in reports]:
        raise ValueError('Stored predictions differ from the specified report sequence')
    if len(rows) != original_runtime['count'] or digest(a.reports) != original_runtime['input_sha256']:
        raise ValueError('Original runtime does not match report data/count')
    root = Path(radplain.__file__).parent
    code = {'radplain/'+x.name:digest(x) for x in sorted(root.glob('*.py'))}
    code['scripts/recheck_v2_outputs.py'] = digest(__file__)
    a.out.mkdir(parents=True)
    summaries = []
    with (a.out/'outputs.jsonl').open('x') as stream:
        for row in rows:
            value = recheck(row['result'])
            stream.write(json.dumps(dict(row, result=value), ensure_ascii=False)+'\n')
            summaries.append(value['postprocessing'])
    runtime = {'stage':a.stage, 'split':a.split, 'mode':'stored-candidate-recheck',
        'count':len(rows), 'original_outputs_sha256':digest(a.input),
        'original_runtime_sha256':digest(a.original_runtime), 'input_sha256':digest(a.reports),
        'candidate_lock_sha256':digest(a.candidate_lock) if a.candidate_lock else None,
        'source_files_sha256':code, 'new_model_calls':0,
        'postprocessing_seconds':sum(r['seconds'] for r in summaries),
        'original_generation_seconds':sum(r['original_generation_seconds'] for r in summaries),
        'note':'Same original semantic verdicts and glossary, no new generation or repair; original compute is retained.'}
    (a.out/'runtime.json').write_text(json.dumps(runtime, ensure_ascii=False, indent=2)+'\n')
    print(json.dumps({k:runtime[k] for k in ('count','new_model_calls','postprocessing_seconds')}))


if __name__ == '__main__':
    main()
